"""Root-side prospective evaluation configuration records."""

import re
from dataclasses import dataclass
from enum import StrEnum

from cocoonet._contracts.execution import ModelFamily, TaskKind
from cocoonet._contracts.identity import (
    ScalarLabel,
    WorkerId,
    validate_identifier,
    validate_label,
)
from cocoonet._type_validation import validate_declared_types


class WorkerKind(StrEnum):
    """Identify the configured execution topology of a worker.

    Attributes
    ----------
    ROOT_LOCAL : str
        Worker explicitly configured on the root machine.
    ONLINE : str
        Worker reached through a later online connection boundary.

    Notes
    -----
    Public/private online ownership is intentionally not represented here.
    Node usage scope: Root - Defines root-side worker topology configuration.
    """

    ROOT_LOCAL = "root-local"
    ONLINE = "online"


@dataclass(frozen=True, kw_only=True, slots=True)
class ModelRegistration:
    """Describe one opaque model input proposed for registration.

    Parameters
    ----------
    model_input : object
        In-memory model candidate or model-file path retained for Phase 3
        registration. Public APIs reject class definitions. File paths are
        normalized by the registry boundary; complete model compatibility is
        validated later by the isolated model adapter.
    model_label : ScalarLabel
        User-provided label that later registry operations require to be
        unique within an evaluation task.
    family : ModelFamily
        Explicitly declared model-construction family.
    task_kind : TaskKind
        Explicitly declared regression or classification task.

    Notes
    -----
    Construction records the supplied values without validating or invoking
    the opaque model input. Validation is a separate configuration boundary.
    Node usage scope: Root - Defines root-side prospective model input.
    """

    model_input: object
    model_label: ScalarLabel
    family: ModelFamily
    task_kind: TaskKind


def validate_model_registration(value: ModelRegistration, /) -> None:
    """Validate one prospective opaque model registration.

    Parameters
    ----------
    value : ModelRegistration
        Candidate model input and its explicitly declared metadata.

    Raises
    ------
    TypeError
        If the record, label, family, or task kind has an incorrect runtime
        type.
    ValueError
        If the opaque model input is ``None``.

    Notes
    -----
    An in-memory candidate is retained without inspection, copying,
    serialization, method access, or family-specific validation. Class
    definitions are invalid because the public API requires a model instance.
    Registry uniqueness, task agreement, file normalization, and later
    family-specific validation belong to their owning boundaries.
    Node usage scope: Root - Validates root-side prospective model input.
    """
    if not isinstance(value, ModelRegistration):
        validate_declared_types(value, expected_type=ModelRegistration)

    if value.model_input is None:
        raise ValueError("model_input must not be None.")
    if isinstance(value.model_input, type):
        raise ValueError(
            "model_input must be an in-memory model instance or a model-file "
            "path; class definitions are not accepted."
        )

    validate_label(value.model_label, field="model_label")
    validate_declared_types(value.family, expected_type=ModelFamily, field="family")
    validate_declared_types(value.task_kind, expected_type=TaskKind, field="task_kind")


@dataclass(frozen=True, kw_only=True, slots=True)
class WorkerConfiguration:
    """Describe one configured root-local or online worker.

    Parameters
    ----------
    worker_id : WorkerId
        Six-character identity generated by the worker from lowercase ASCII
        letters and decimal digits. It is expected to be unique among workers
        and is the authoritative worker-registry index.
    worker_label : ScalarLabel
        User-configured worker-side label exposed as descriptive metadata.
        Labels may be duplicated and are not worker-registry indices.
    kind : WorkerKind
        Topology used to set up a root-local or online worker.
    device : str, default="cpu"
        Fixed worker-machine device property configured and validated by the
        worker.
    cpu_capacity : int | None, default=None
        Fixed number of logical CPU cores available on the worker machine.
        ``None`` represents capacity not yet supplied by the worker.
    n_attempt : int, default=1
        Positive maximum number of parallel attempts configured for execution.
    n_cpu_per_attempt : int, default=1
        Positive number of logical CPU cores requested for each attempt.
    memory_reserve_pct : float, default=20.0
        Percentage of worker memory reserved when deciding whether another
        parallel attempt may safely start.

    Notes
    -----
    ``device`` and ``cpu_capacity`` describe the worker machine.
    ``n_attempt``, ``n_cpu_per_attempt``, and ``memory_reserve_pct`` describe
    execution configuration. This record does not establish connectivity,
    heartbeat availability, compatibility, or effective attempt capacity.
    Node usage scope: Shared - Carries worker-owned identity and machine
    properties together with root-selected execution configuration.
    """

    worker_id: WorkerId
    worker_label: ScalarLabel
    kind: WorkerKind
    device: str = "cpu"
    cpu_capacity: int | None = None
    n_attempt: int = 1
    n_cpu_per_attempt: int = 1
    memory_reserve_pct: float = 20.0


def validate_worker_configuration(value: WorkerConfiguration, /) -> None:
    """Validate one worker configuration.

    Parameters
    ----------
    value : WorkerConfiguration
        Candidate worker identity, machine properties, topology, and execution
        configuration.

    Raises
    ------
    TypeError
        If the record or one of its fields has an incorrect runtime type.
    ValueError
        If the worker ID is not six lowercase alphanumeric characters, the
        label or device is empty, a configured capacity is not positive, or
        the memory reserve is outside zero through one hundred percent.

    Notes
    -----
    Worker-ID uniqueness is a registry-wide invariant and is therefore not
    established by validating one record. Worker labels may be duplicated.
    This validation does not probe connectivity, detect hardware, calculate
    effective capacity, or validate worker availability.
    Node usage scope: Shared - Validates worker-supplied properties and
    task-specific execution configuration without performing worker I/O.
    """
    if not isinstance(value, WorkerConfiguration):
        validate_declared_types(value, expected_type=WorkerConfiguration)

    validate_identifier(value.worker_id, field="worker_id")
    if re.fullmatch(r"[a-z0-9]{6}", value.worker_id) is None:
        raise ValueError(
            "worker_id must contain exactly six lowercase ASCII letters or " f"decimal digits; got {value.worker_id!r}."
        )

    validate_label(value.worker_label, field="worker_label")
    validate_declared_types(value.kind, expected_type=WorkerKind, field="kind")

    validate_declared_types(value.device, expected_type=str, field="device")
    if not value.device:
        raise ValueError("device must be a nonempty string; got an empty string.")

    if value.cpu_capacity is not None:
        validate_declared_types(
            value.cpu_capacity,
            expected_type=int,
            field="cpu_capacity",
        )
        if value.cpu_capacity < 1:
            raise ValueError("cpu_capacity must be a positive integer or None; " f"got {value.cpu_capacity!r}.")

    validate_declared_types(value.n_attempt, expected_type=int, field="n_attempt")
    if value.n_attempt < 1:
        raise ValueError(f"n_attempt must be a positive integer; got {value.n_attempt!r}.")

    validate_declared_types(
        value.n_cpu_per_attempt,
        expected_type=int,
        field="n_cpu_per_attempt",
    )
    if value.n_cpu_per_attempt < 1:
        raise ValueError("n_cpu_per_attempt must be a positive integer; " f"got {value.n_cpu_per_attempt!r}.")

    validate_declared_types(
        value.memory_reserve_pct,
        expected_type=float,
        field="memory_reserve_pct",
    )
    if not 0.0 <= value.memory_reserve_pct <= 100.0:
        raise ValueError(
            "memory_reserve_pct must be between 0.0 and 100.0 inclusive; " f"got {value.memory_reserve_pct!r}."
        )
